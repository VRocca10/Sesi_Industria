const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const assert = require('node:assert/strict')
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5174'

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    const errors = []
    const apiRequests = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('request', (request) => {
      const url = new URL(request.url())
      if (url.pathname.startsWith('/api/')) apiRequests.push(url)
    })
    await page.goto(`${base}/cursos?categoria=inexistente&modalidade=inexistente&status=inexistente&origem=teste`)
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    await page.waitForURL((url) => !url.searchParams.has('categoria') && !url.searchParams.has('modalidade') && !url.searchParams.has('status'))
    assert.equal(new URL(page.url()).searchParams.get('origem'), 'teste')
    assert.equal(await page.getByRole('combobox', { name: 'Status', exact: true }).innerText(), 'Todos os status')
    await page.goto(`${base}/cursos?busca=FISICA&categoria=ciencias-natureza&status=inexistente`)
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    await page.waitForURL((url) => !url.searchParams.has('status'))
    assert.equal(new URL(page.url()).searchParams.get('busca'), 'FISICA')
    assert.equal(new URL(page.url()).searchParams.get('categoria'), 'ciencias-natureza')
    await page.goto(`${base}/cursos`)
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    const search = page.getByLabel('Nome do curso', { exact: true })
    await search.click()
    await search.pressSequentially('matematica para a precisao', { delay: 50 })
    assert.equal(await search.inputValue(), 'matematica para a precisao')
    assert.equal(await search.evaluate((input) => document.activeElement === input), true)
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    assert.ok(apiRequests.some((url) => url.searchParams.get('search') === 'matematica para a precisao'))
    await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click()
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    await page.getByLabel('Nome do curso', { exact: true }).fill('FISICA')
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    async function selectFilter(label, option) {
      await page.getByRole('combobox', { name: label, exact: true }).click()
      await page.getByRole('option', { name: option, exact: true }).click()
    }
    await selectFilter('Categoria', 'Ciências da natureza')
    await selectFilter('Modalidade', 'Semipresencial')
    await selectFilter('Status', 'Disponível')
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    assert.equal(await page.locator('.course-catalog-grid article').count(), 1)
    await page.reload()
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    await selectFilter('Status', 'Encerrado')
    await page.getByRole('heading', { name: 'Nenhum curso encontrado' }).waitFor()
    await page.getByRole('button', { name: 'Limpar filtros e ver cursos', exact: true }).click()
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Nome do curso', { exact: true }).inputValue(), '')
    const category = page.getByRole('combobox', { name: 'Categoria', exact: true })
    await category.focus()
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('l')
    await page.keyboard.press('Enter')
    await page.getByText('1 curso encontrado', { exact: true }).waitFor()
    assert.equal(await category.getAttribute('aria-expanded'), 'false')
    await category.click()
    const fieldBox = await category.boundingBox()
    const menuBox = await page.getByRole('listbox').boundingBox()
    assert.ok(Math.abs(menuBox.y - (fieldBox.y + fieldBox.height) - 4) < 1)
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click()
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    for (const width of [320, 375, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow ${width}`)
    }
    await page.getByRole('link', { name: 'Física na Metalurgia', exact: true }).click()
    await page.getByRole('heading', { name: 'Física do Movimento e da Energia na Metalurgia', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Reproduzir apresentação do curso' }).click()
    await page.getByRole('dialog').getByRole('heading', { name: 'Apresentação do curso', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Fechar vídeo' }).click()
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.equal(await page.getByRole('link', { name: 'Matricule-se', exact: true }).count(), 2)
    await page.getByRole('link', { name: 'Matricule-se', exact: true }).first().click()
    await page.locator('.learning-course-name').getByText('Física do Movimento e da Energia na Metalurgia', { exact: true }).waitFor()
    const lessonSearch = page.getByRole('searchbox', { name: 'Buscar aulas' })
    await page.getByText('3. Módulo 2', { exact: true }).click()
    await page.getByRole('button', { name: '3.2 Eficiência energética', exact: true }).waitFor()
    await lessonSearch.fill('eficiencia')
    await page.getByRole('button', { name: '3.2 Eficiência energética', exact: true }).waitFor()
    await page.getByRole('button', { name: /Eficiência energética/ }).click()
    await page.getByRole('heading', { name: 'Eficiência energética', exact: true }).waitFor()
    await lessonSearch.fill('aula inexistente')
    await page.getByText('Nenhuma aula encontrada.', { exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Eficiência energética', exact: true }).waitFor()
    await lessonSearch.fill('')
    await page.getByRole('button', { name: '1.2 Boas práticas', exact: true }).click()
    await page.getByRole('heading', { name: 'Boas práticas', exact: true }).waitFor()
    for (const id of ['estatistica-qualidade', 'quimica-sustentabilidade']) {
      await page.goto(`${base}/cursos/${id}`)
      await page.locator('.course-enroll-action:disabled').first().waitFor()
      assert.equal(await page.getByRole('link', { name: 'Matricule-se', exact: true }).count(), 0)
      assert.equal(await page.locator('.course-enroll-action:disabled').count(), 2)
      await page.goto(`${base}/aprender/${id}`)
      await page.waitForURL(`${base}/cursos/${id}`)
      await page.locator('.course-enroll-action:disabled').first().waitFor()
      assert.equal(await page.locator('.learning-page').count(), 0)
      assert.equal(await page.locator('.course-enroll-action:disabled').count(), 2)
      await page.reload()
      assert.equal(await page.locator('.learning-page').count(), 0)
    }
    assert.deepEqual(errors, [])
    const failurePage = await browser.newPage()
    let releaseRequest
    const requestGate = new Promise((resolve) => { releaseRequest = resolve })
    let fail = true
    await failurePage.route(/\/api\/courses(?:\?.*)?$/, async (route) => {
      await requestGate
      if (!fail) return route.continue()
      await route.fulfill({ status: 503, contentType: 'application/problem+json', headers: { 'access-control-allow-origin': new URL(base).origin }, body: JSON.stringify({ status: 503, title: 'Falha simulada' }) })
    })
    await failurePage.goto(`${base}/cursos`)
    await failurePage.getByText('Carregando cursos…', { exact: true }).waitFor()
    releaseRequest()
    await failurePage.getByRole('heading', { name: 'Não foi possível carregar os cursos' }).waitFor()
    fail = false
    await failurePage.getByRole('button', { name: 'Tentar novamente' }).click()
    await failurePage.getByText('6 cursos encontrados', { exact: true }).waitFor()
    await page.goto(`${base}/cursos`)
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    await page.getByRole('link', { name: 'Pular para o conteúdo', exact: true }).focus()
    assert.equal(await page.locator(':focus').textContent(), 'Pular para o conteúdo')
    await page.keyboard.press('Enter')
    assert.equal(await page.locator(':focus').getAttribute('id'), 'conteudo')
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    await page.goto(`${base}/`)
    await page.getByRole('button', { name: 'Reproduzir vídeo de apresentação', exact: true }).click()
    await page.getByRole('dialog').getByRole('heading', { name: 'Conheça a capacitação SESI', exact: true }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('dialog').count(), 0)
    await page.goto(`${base}/cursos`)
    await page.getByText('6 cursos encontrados', { exact: true }).waitFor()
    if (process.env.TEST_SCREENSHOT) await page.screenshot({ path: process.env.TEST_SCREENSHOT, fullPage: true })
    assert.deepEqual(errors, [])
    assert.ok(apiRequests.some((url) => url.pathname === '/api/categories'))
    assert.ok(apiRequests.some((url) => url.pathname === '/api/courses/fisica-metalurgia'))
    assert.ok(apiRequests.some((url) => url.searchParams.get('category') === 'ciencias-natureza' && url.searchParams.get('modality') === 'Semipresencial' && url.searchParams.get('status') === 'Disponível'))
    console.log('PASS: catálogo, filtros, digitação contínua, URL, estados, teclado, 5 larguras, matrícula, vídeos e navegação/pesquisa de aulas.')
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
